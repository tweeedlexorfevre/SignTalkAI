-- SignTalk messenger schema (PostgreSQL / Supabase). Applied on every start; every statement is idempotent.
-- Timestamps are milliseconds since the Unix epoch (bigint), exactly like the SQLite version.
--
-- Only the server talks to these tables, over a direct Postgres connection (DATABASE_URL).
-- Row Level Security is on with no policies and the Supabase API roles have no grants,
-- so nothing (password hashes included) is reachable through the public Supabase REST API.

-- Accounts. public_id is the unique ID people share to find each other (e.g. ST-7KQ2MX).
CREATE TABLE IF NOT EXISTS users (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id     text   NOT NULL UNIQUE,
  username      text   NOT NULL,
  display_name  text   NOT NULL,
  password_hash text   NOT NULL,
  created_at    bigint NOT NULL
);
-- Usernames are unique case-insensitively (SQLite: COLLATE NOCASE).
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower ON users (lower(username));

-- One row per signed-in device. Only a SHA-256 of the bearer token is stored.
CREATE TABLE IF NOT EXISTS sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash   text   NOT NULL UNIQUE,
  device_name  text   NOT NULL,
  created_at   bigint NOT NULL,
  last_seen_at bigint NOT NULL,
  revoked_at   bigint
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

-- Address book: owner_id saved contact_id.
CREATE TABLE IF NOT EXISTS contacts (
  owner_id   bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  contact_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at bigint NOT NULL,
  PRIMARY KEY (owner_id, contact_id),
  CHECK (owner_id <> contact_id)
);
CREATE INDEX IF NOT EXISTS contacts_contact ON contacts(contact_id);

-- Direct messages. kind: text (typed), sign (recognised sign), speech (speech-to-text), call (call log, body is JSON).
CREATE TABLE IF NOT EXISTS messages (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id    bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind         text   NOT NULL CHECK (kind IN ('text', 'sign', 'speech', 'call')),
  body         text   NOT NULL,
  created_at   bigint NOT NULL,
  read_at      bigint
);
CREATE INDEX IF NOT EXISTS messages_pair ON messages(sender_id, recipient_id, id);
CREATE INDEX IF NOT EXISTS messages_unread ON messages(recipient_id, read_at);

-- Video calls, one row per call attempt.
CREATE TABLE IF NOT EXISTS calls (
  id          text   PRIMARY KEY,
  caller_id   bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  callee_id   bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status      text   NOT NULL CHECK (status IN ('ringing', 'active', 'completed', 'missed', 'declined', 'cancelled', 'busy', 'failed')),
  created_at  bigint NOT NULL,
  answered_at bigint,
  ended_at    bigint
);
CREATE INDEX IF NOT EXISTS calls_caller ON calls(caller_id);
CREATE INDEX IF NOT EXISTS calls_callee ON calls(callee_id);

-- Lock the tables away from the Supabase REST/GraphQL API (anon and signed-in API users).
ALTER TABLE users    ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE calls    ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON users, sessions, contacts, messages, calls FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON users, sessions, contacts, messages, calls FROM authenticated;
  END IF;
END $$;
