export function readFavorites(raw: string | null): string[] {
  try {
    const value: unknown = JSON.parse(raw ?? '[]');
    return Array.isArray(value)
      ? value
          .filter(
            (v): v is string => typeof v === 'string' && v.trim().length > 0 && v.length <= 150,
          )
          .slice(0, 12)
      : [];
  } catch {
    return [];
  }
}
